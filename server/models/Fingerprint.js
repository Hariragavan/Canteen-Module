import mongoose from 'mongoose';

const SingleFingerSchema = new mongoose.Schema(
  {
    fingerName: {
      type: String,
      required: true,
      default: 'Right Thumb', // e.g. Right Thumb, Right Index, Left Thumb, Left Index
    },
    isoTemplate: {
      type: String,
      required: true, // Base64 encoded ISO 19794-2 template generated by Mantra MFS100
    },
    ansiTemplate: {
      type: String,
      default: '',
    },
    bitmapData: {
      type: String,
      default: '', // Base64 fingerprint thumbnail for visual preview in admin
    },
    quality: {
      type: Number,
      default: 0, // Quality score (0 - 100)
    },
  },
  { _id: false }
);

const FingerprintSchema = new mongoose.Schema(
  {
    employeeId: {
      type: String,
      required: true,
      unique: true,
      trim: true,
      index: true, // Linked to Employee.id
    },
    employeeName: {
      type: String,
      default: '',
      trim: true,
    },
    dept: {
      type: String,
      default: 'Employee',
      trim: true,
    },
    // Primary Finger
    finger1: {
      type: SingleFingerSchema,
      required: true,
    },
    // Secondary Backup Finger
    finger2: {
      type: SingleFingerSchema,
      required: true,
    },
    deviceModel: {
      type: String,
      default: 'Mantra MFS100',
    },
    isActive: {
      type: Boolean,
      default: true,
      index: true,
    },
  },
  {
    timestamps: true,
    collection: 'fingerprints',
  }
);

export const Fingerprint =
  mongoose.models.Fingerprint || mongoose.model('Fingerprint', FingerprintSchema);
